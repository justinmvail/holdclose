  // ──────────────────── helpers ────────────────────

  String _whatWorked(JournalEntry entry) {
    switch (entry.outcome) {
      case JournalOutcome.positive:
        if (entry.result.tweak.isNotEmpty) return entry.result.tweak.first;
        if (entry.result.say.isNotEmpty) return entry.result.say.first;
        return 'That helped.';
      case JournalOutcome.triedDifferent:
        return 'Tried a different approach.';
      case JournalOutcome.error:
        return "Couldn't reach the coach.";
      case JournalOutcome.pending:
        return '(no outcome logged)';
    }
  }

  List<_BehaviorTally> _tally(List<JournalEntry> entries) {
    final Map<String, _BehaviorTally> counts = <String, _BehaviorTally>{};
    for (final JournalEntry e in entries) {
      final _BehaviorTally? prior = counts[e.behavior.id];
      counts[e.behavior.id] = _BehaviorTally(
        id: e.behavior.id,
        label: e.behavior.label,
        count: (prior?.count ?? 0) + 1,
      );
    }
    final List<_BehaviorTally> sorted = counts.values.toList()
      ..sort((_BehaviorTally a, _BehaviorTally b) {
        final int byCount = b.count.compareTo(a.count);
        if (byCount != 0) return byCount;
        return a.label.compareTo(b.label);
      });
    return sorted;
  }
}

@immutable
class _BehaviorTally {
  const _BehaviorTally({
    required this.id,
    required this.label,
    required this.count,
  });

  final String id;
  final String label;
  final int count;
}

/// One row in the "Active medications" PDF section (BUILD_SPEC.md Phase
/// 12.8, v14 windows pivot).
///
/// Pairs the [Medication] with the (window, entry) pairs it
/// participates in so the exporter can render a human-readable
/// summary ("Morning · Bedtime") without re-querying drift mid-render.
@immutable
class MedicationWithSchedules {
  const MedicationWithSchedules({
    required this.medication,
    required this.windows,
  });

  final Medication medication;

  /// One entry per window this medication appears in. The exporter
  /// joins the window labels for the summary cell.
  final List<({DoseWindow window, MedicationWindowEntry entry})> windows;
}

/// One row in the "Upcoming appointments" PDF section (BUILD_SPEC.md
/// Phase 12.8).
///
/// Pairs the [Appointment] with its [Provider] (when known) so the
/// exporter can render "Dr. Patel, Neurologist — Jun 4 2026, 10:00 AM"
/// without joining tables at render time. The provider is nullable for
/// the rare case where a provider was deleted but its appointment row
/// survived (DB FK should cascade, but defending here keeps the render
/// path total).
@immutable
class AppointmentWithProvider {
  const AppointmentWithProvider({
    required this.appointment,
    required this.provider,
  });

  final Appointment appointment;
  final Provider? provider;
}

// Brand tokens duplicated as `PdfColor` values rather than imported from
// `lib/theme.dart` — the Flutter `Color` type isn't usable inside the
// `pdf` package's `widgets.dart` painter. The hex values match
