/// Half-open `[start, end)` window for the journal PDF export
/// (BUILD_SPEC.md §5.5 doctor-visit packet).
///
/// The journal screen passes the same window the on-screen stream uses
/// (defaults to "last 30 days"); the exporter filters entries to those
/// whose [JournalEntry.createdAt] falls inside the range.
@immutable
class DateRange {
  const DateRange({required this.start, required this.end});

  final DateTime start;
  final DateTime end;

  bool contains(DateTime t) => !t.isBefore(start) && t.isBefore(end);

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      (other is DateRange && other.start == start && other.end == end);

  @override
  int get hashCode => Object.hash(start, end);
}

/// Generates the two v1 PDF artifacts (BUILD_SPEC.md §5.5 + §5.9).
///
/// * [exportRange] — the multi-page "doctor visit packet" the caregiver
///   shares from the journal screen: cover page, behavior summary table,
///   chronological entry log, footer disclaimer.
/// * [crisisCard] — the single-page hospital handoff sheet from the
///   crisis card screen: every [Patient] field from BUILD_SPEC.md §9.1
///   on one page with the "Updated" timestamp + medical-advice footer.
///
/// Both methods return a [Uint8List] so callers can decide what to do
/// with it (share, save, preview). [sharePdf] is the convenience wrapper
/// the journal + crisis screens use to drop straight into the OS share
/// sheet via `printing`.
///
/// [compress] is plumbed through to [pw.Document] so tests can build the
/// PDF with stream compression disabled and assert that a specific
/// substring made it into the byte buffer. Production callers leave it
/// at the default.
class PdfExporter {
  const PdfExporter({this.compress = true, this.clock = DateTime.now});

  final bool compress;
  final DateTime Function() clock;

  /// Always-visible per-page footer (BUILD_SPEC.md §5.5 + §13.1).
  static const String footerDisclaimer =
      'Generated by Careblazers. Not a substitute for medical advice.';

  /// Generate the doctor-visit packet for [entries] filtered to [range].
  /// [caregiverName] is rendered on the cover (falls back to the
  /// patient's primary caregiver name when omitted).
  ///
  /// BUILD_SPEC.md Phase 12.8 — when [medications] or [appointments]
  /// is provided, the packet appends "Active medications" and
  /// "Upcoming appointments" sections respectively. Both lists are
  /// optional so the journal export path can call this without the
  /// tracker tables loaded (the lean-app mode); the crisis card path
  /// still relies on the [Patient.medications] free-text list per
  /// BUILD_SPEC.md §9.1.
  Future<Uint8List> exportRange({
    required List<JournalEntry> entries,
    required Patient patient,
    required DateRange range,
    String? caregiverName,
    List<MedicationWithSchedules> medications =
        const <MedicationWithSchedules>[],
    List<AppointmentWithProvider> appointments =
        const <AppointmentWithProvider>[],
  }) async {
    final pw.Document doc = pw.Document(compress: compress);
    final List<JournalEntry> windowed = entries
        .where((JournalEntry e) => range.contains(e.createdAt))
        .toList()
      ..sort((JournalEntry a, JournalEntry b) =>
          b.createdAt.compareTo(a.createdAt));
    final List<_BehaviorTally> tallies = _tally(windowed);
    final String caregiver =
        caregiverName ?? patient.primaryCaregiver.name;
    final DateTime now = clock();
    final List<AppointmentWithProvider> upcoming = appointments
        .where((AppointmentWithProvider a) =>
            a.appointment.status == AppointmentStatus.upcoming &&
            !a.appointment.startsAt.isBefore(now))
        .toList()
      ..sort((AppointmentWithProvider a, AppointmentWithProvider b) =>
          a.appointment.startsAt.compareTo(b.appointment.startsAt));

    doc.addPage(
      pw.MultiPage(
        margin: const pw.EdgeInsets.symmetric(horizontal: 36, vertical: 48),
        footer: _pageFooter,
        build: (pw.Context ctx) => <pw.Widget>[
          _cover(
            patient: patient,
            range: range,
            caregiverName: caregiver,
            entryCount: windowed.length,
          ),
          pw.SizedBox(height: 24),
          _summaryTable(tallies),
          if (medications.isNotEmpty) ...<pw.Widget>[
            pw.SizedBox(height: 24),
            _medicationsHeading(medications.length),
            pw.SizedBox(height: 8),
            _medicationsTable(medications),
          ],
          if (upcoming.isNotEmpty) ...<pw.Widget>[
            pw.SizedBox(height: 24),
            _appointmentsHeading(upcoming.length),
            pw.SizedBox(height: 8),
            _appointmentsTable(upcoming),
          ],
          pw.SizedBox(height: 24),
          _entriesHeading(windowed.length),
          pw.SizedBox(height: 8),
          ..._entryRows(windowed),
        ],
      ),
    );

    return doc.save();
  }

  /// Generate the one-page hospital handoff card (BUILD_SPEC.md §5.9 +
  /// §9.1). The page carries every [Patient] field so paramedics can
  /// orient from this sheet alone.
  Future<Uint8List> crisisCard(Patient patient) async {
    final pw.Document doc = pw.Document(compress: compress);
    doc.addPage(
      pw.Page(
        margin: const pw.EdgeInsets.symmetric(horizontal: 36, vertical: 48),
        build: (pw.Context ctx) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: <pw.Widget>[
            _crisisHeader(patient),
            pw.SizedBox(height: 16),
            _crisisDiagnosis(patient),
            pw.SizedBox(height: 14),
            _crisisMedications(patient),
            pw.SizedBox(height: 14),
            _crisisAllergies(patient),
            pw.SizedBox(height: 14),
            _crisisBulletGroup('What calms her:', patient.calms),
            pw.SizedBox(height: 14),
            _crisisBulletGroup('What escalates her:', patient.escalates),
            pw.SizedBox(height: 14),
            _crisisContacts(patient),
            pw.SizedBox(height: 14),
            _crisisDirective(patient),
            pw.Spacer(),
            _crisisFooter(),
          ],
        ),
      ),
    );
    return doc.save();
  }

  /// Hand [bytes] to the OS share sheet via `printing`. Thin wrapper so
  /// the journal + crisis screens depend on a single seam rather than
  /// importing `printing` directly.
  Future<bool> sharePdf(Uint8List bytes, {String filename = 'careblazers.pdf'}) {
    return Printing.sharePdf(bytes: bytes, filename: filename);
  }

